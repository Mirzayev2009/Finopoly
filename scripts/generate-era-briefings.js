// Regenerates packages/content/era-briefings.js as a fully STATIC file with
// no import of eras.js. This is deliberate, not a style choice: a
// runtime `ERAS.map(strip)` derivation would still force the whole eras.js
// module (all 720 investment cards, percentages included) into any bundle
// that imports ERA_BRIEFINGS, since a bundler traces the import graph, not
// which object properties end up used. Run whenever eras.js's non-
// investment fields change: node scripts/generate-era-briefings.js
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ERAS } from '../packages/content/eras.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outPath = path.join(__dirname, '..', 'packages', 'content', 'era-briefings.js');

const briefings = ERAS.map(({ investments, ...rest }) => rest);

const header = `/**
 * GENERATED by scripts/generate-era-briefings.js — do not hand-edit.
 * Client-safe view of ERAS: every field except `;
const header2 = `\`investments\`. Deliberately a static
 * literal with NO import of eras.js — apps/web imports this file (never
 * eras.js directly), and a bundler only pulls in what's actually imported.
 * If this file re-derived ERA_BRIEFINGS from ERAS at runtime instead, the
 * whole eras.js module (all 720 investment cards, percentages included)
 * would end up shipped in the client bundle regardless of which properties
 * the derived value actually uses — confirmed by inspecting a real build.
 * Regenerate after any non-investment change to an era in eras.js.
 */
export const ERA_BRIEFINGS = `;

writeFileSync(outPath, `${header}${header2}${JSON.stringify(briefings, null, 2)};\n`);
console.log(`Wrote ${briefings.length} era briefings to ${outPath}`);
